"""Generate the fixed 16x16 bitmap phrase used by the SW3 text overlay.

Uses the locally installed SimHei font through Pillow. Generated Verilog is
self-contained: FPGA builds and playback do not require a font file.
"""
from pathlib import Path
import argparse
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TEXT = 'fpga真有意思，真好玩'

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--font', default='C:/Windows/Fonts/simhei.ttf')
    args = parser.parse_args()
    font = ImageFont.truetype(args.font, 16)
    rows = []
    preview = Image.new('RGB', (16 * len(TEXT), 16), 'black')
    for index, char in enumerate(TEXT):
        glyph = Image.new('L', (16, 16))
        draw = ImageDraw.Draw(glyph)
        bounds = draw.textbbox((0, 0), char, font=font)
        # Preserve baseline for Latin descenders; Chinese occupies 16x16.
        x = (16 - (bounds[2] - bounds[0])) // 2 - bounds[0]
        draw.text((x, -2), char, fill=255, font=font)
        glyph = glyph.point(lambda v: 255 if v >= 96 else 0)
        preview.paste(Image.merge('RGB', (glyph, glyph, glyph)), (index*16, 0))
        for y in range(16):
            bits = sum((1 << (15-x)) for x in range(16) if glyph.getpixel((x,y)))
            rows.append(f"            8'd{index*16+y}: row_bits = 16'h{bits:04X};")
    source = '''`timescale 1ns/1ps
// Generated by tools/generate_scroll_font.py. Phrase: fpga真有意思，真好玩
// Fixed 12 cells x 16 rows; leftmost pixel is bit 15.
module scroll_text_font(input [7:0] address, output reg [15:0] row_bits);
always @* begin
    case(address)
'''+ '\n'.join(rows) + '''
            default: row_bits = 16'd0;
    endcase
end
endmodule
'''
    (ROOT/'user_source/hdl_source/tfmedia3/scroll_text_font.v').write_text(source, encoding='utf-8')
    folder=ROOT/'output/scroll-text-preview'
    folder.mkdir(parents=True,exist_ok=True)
    preview.resize((16*len(TEXT)*3,48),Image.Resampling.NEAREST).save(folder/'font.png')
    print(f'Generated {len(TEXT)} glyphs, {len(rows)*16} bitmap bits: {TEXT}')

if __name__ == '__main__':
    main()
